returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if (new.title, new.kind, new.content, new.is_published, new.source_filename)
     is distinct from (old.title, old.kind, old.content, old.is_published, old.source_filename) then
    new.updated_at = now();
