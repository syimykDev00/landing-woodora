    execute format('alter table public.%I enable row level security', t);
    execute format('revoke all on public.%I from anon, authenticated', t);
  end loop;
end;
$$;

-- Полный CRUD для администратора
do $$
declare
  t text;
begin
  foreach t in array array['clients', 'products', 'services', 'applications', 'orders', 'order_items', 'kb_documents']
  loop
    execute format('grant select, insert, update, delete on public.%I to authenticated', t);
    execute format('create policy %I on public.%I for all to authenticated using ((select public.is_admin())) with check ((select public.is_admin()))',
                   'admin_all_' || t, t);
  end loop;
end;
$$;

