-- Гибридный поиск: полнотекстовый (всегда) + векторный (если передан embedding вопроса).
-- Итог — Reciprocal Rank Fusion двух списков. Ищет только по опубликованным документам.
create or replace function public.match_kb_chunks(
  query_text text,
  query_embedding extensions.vector(1536) default null,
  match_count integer default 6
)
returns table (chunk_id bigint, document_id bigint, title text, kind text, content text, score double precision)
language sql
stable
set search_path = ''
as $$
  with q as (
    -- Слова вопроса через ИЛИ: «сколько стоит доставка» находит фрагмент со словом «доставка»
    select nullif(replace(plainto_tsquery('russian', query_text)::text, '&', '|'), '')::tsquery as tsq
  ),
  fts as (
    select c.id, row_number() over (order by ts_rank_cd(c.tsv, q.tsq) desc) as rnk
      from public.kb_chunks c
      join public.kb_documents d on d.id = c.document_id and d.is_published
      cross join q
     where q.tsq is not null and c.tsv @@ q.tsq
     order by ts_rank_cd(c.tsv, q.tsq) desc
     limit 20
  ),
  vec as (
    select c.id, row_number() over (order by c.embedding operator(extensions.<=>) query_embedding) as rnk
      from public.kb_chunks c
      join public.kb_documents d on d.id = c.document_id and d.is_published
     where query_embedding is not null and c.embedding is not null
       and (c.embedding operator(extensions.<=>) query_embedding) < 0.75
     order by c.embedding operator(extensions.<=>) query_embedding
     limit 20
  ),
  fused as (
    select coalesce(fts.id, vec.id) as id,
           coalesce(1.0 / (60 + fts.rnk), 0) + coalesce(1.0 / (60 + vec.rnk), 0) as score
      from fts full outer join vec on fts.id = vec.id
  )
  select c.id, c.document_id, d.title, d.kind, c.content, f.score::double precision
    from fused f
    join public.kb_chunks c on c.id = f.id
    join public.kb_documents d on d.id = c.document_id
   order by f.score desc
   limit greatest(1, least(match_count, 12));
$$;

revoke all on function public.match_kb_chunks(text, extensions.vector, integer) from public, anon, authenticated;

