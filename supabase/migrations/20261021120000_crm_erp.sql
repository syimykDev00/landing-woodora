-- Сумма заказа всегда равна сумме позиций
create or replace function public.recalc_order_total()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  target bigint := coalesce(new.order_id, old.order_id);
begin
  update public.orders o
     set total = coalesce((select sum(i.unit_price * i.quantity) from public.order_items i where i.order_id = target), 0)
   where o.id = target;
  if tg_op = 'UPDATE' and old.order_id <> new.order_id then
    update public.orders o
       set total = coalesce((select sum(i.unit_price * i.quantity) from public.order_items i where i.order_id = old.order_id), 0)
     where o.id = old.order_id;
  end if;
  return null;
end;
$$;

revoke all on function public.recalc_order_total() from public, anon, authenticated;

